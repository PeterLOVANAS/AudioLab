-- AudioLab 2.0 — Migration 0005: concrete annotation jobs.
--
-- DO NOT rename or edit after applying. D1 tracks migration filenames.
-- This table contains neither Labeller answers nor MMAU reference answers.
-- A task instance is a *request to annotate* a single audio asset under
-- a published, immutable Task Definition version.

CREATE TABLE task_instances (
  id TEXT PRIMARY KEY,

  -- Project owns the annotation task. The service also checks that both
  -- its definition AND recording belong to this exact project.
  project_id TEXT NOT NULL,

  -- Use the historical published snapshot, not the editable draft.
  definition_id TEXT NOT NULL,
  definition_version INTEGER NOT NULL CHECK (definition_version >= 1),

  -- An existing audio_assets row. The actual WAV remains in R2.
  asset_id TEXT NOT NULL,

  -- Optional link to an imported MMAU question (not its answer).
  -- This is source_records.id, NOT source_records.source_record_id.
  source_record_db_id TEXT,

  -- Distinguishes multiple questions/tasks using the same audio, version.
  -- 'audio' means no linked source question; 'source:<sourceRecordId>'
  -- means a specific imported question. Generated by the service.
  instance_key TEXT NOT NULL,

  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

  FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE RESTRICT,
  FOREIGN KEY (asset_id) REFERENCES audio_assets(id) ON DELETE RESTRICT,
  FOREIGN KEY (definition_id, definition_version)
    REFERENCES task_definition_versions(definition_id, version)
    ON DELETE RESTRICT,
  FOREIGN KEY (source_record_db_id) REFERENCES source_records(id)
    ON DELETE RESTRICT,

  -- Retried ingestion cannot silently create identical tasks.
  UNIQUE (definition_id, definition_version, asset_id, instance_key)
);

-- List tasks efficiently for a project or a particular dataset.
CREATE INDEX idx_task_instances_project_created
  ON task_instances(project_id, created_at, id);
CREATE INDEX idx_task_instances_asset
  ON task_instances(asset_id);
CREATE INDEX idx_task_instances_definition_version
  ON task_instances(definition_id, definition_version);
