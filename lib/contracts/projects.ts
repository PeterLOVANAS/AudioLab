
/*
 * AudioLab 2.0 — Project contract
 *
 * A Project represents a research workspace.
 * Other entities, such as datasets and tasks,
 * will belong to a project.
 */

export type Project = {
  id: string; // Unique identifier for the project, generated by the backend.
  name: string;
  slug: string; 
};

// When creating a project, the client does not
// provide an ID. The backend generates it.
export type CreateProjectInput = Omit<Project, "id">; // Omit id when constructing a new project because The backend generates the id.
// What is Omit? Omit is a utility type in TypeScript that constructs a new type by excluding certain properties from an existing type. In this case, CreateProjectInput is a new type that includes all properties of the Project type except for the "id" property. This is useful when creating a new project, as the client does not provide an ID; instead, the backend generates it.